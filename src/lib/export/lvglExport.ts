function toPascalCase(raw: string): string {
  const words = raw
    .replace(/[^a-zA-Z0-9]+/g, ' ')
    .replace(/([a-z0-9])([A-Z])/g, '$1 $2')
    .trim()
    .split(/\s+/)
    .filter(Boolean)
  if (words.length === 0) return 'Widget'
  return words.map((w) => w[0].toUpperCase() + w.slice(1)).join('')
}

function toCIdentifier(raw: string): string {
  const cleaned = raw.replace(/[^a-zA-Z0-9_]/g, '_').replace(/^([0-9])/, '_$1')
  return cleaned || '_'
}

// ---- Variable Manager naming (see types/uiDesign.ts's UiVariable + scriptLang/codegen.ts's
// CodegenContext.identForVariableName, which resolves a `data.<name>` reference in script to
// these exact identifiers) ----
function uiVariableExprType(type: UiVariable['type']): ExprType {
  if (type === 'number') return 'number'
  if (type === 'boolean') return 'boolean'
  return 'String' // text/color/list/image/object — String is the practical default for anything not a plain number/bool
}
function variableVarName(v: UiVariable): string {
  return `g_var_${toCIdentifier(v.name)}`
}
function variableGetterName(v: UiVariable): string {
  return `Get${toPascalCase(v.name)}`
}
function variableSetterName(v: UiVariable): string {
  return `Set${toPascalCase(v.name)}`
}
function variableDefaultLiteral(v: UiVariable): string {
  if (v.type === 'number') return String(typeof v.defaultValue === 'number' ? v.defaultValue : 0)
  if (v.type === 'boolean') return v.defaultValue ? 'true' : 'false'
  return JSON.stringify(String(v.defaultValue ?? ''))
}

/** snake_case identifier — used only by the "UI Screen Only" export mode's public
 * `create_<screen>_screen()`/`show_<screen>_screen()` function names, per that mode's own
 * explicit naming spec (deliberately different from the rest of this file's PascalCase
 * `KiboUI::CreateXxxScreen()` convention — see the "naming continuity" note where this is used). */
function toSnakeCase(raw: string): string {
  const words = raw
    .replace(/[^a-zA-Z0-9]+/g, ' ')
    .replace(/([a-z0-9])([A-Z])/g, '$1 $2')
    .trim()
    .split(/\s+/)
    .filter(Boolean)
  if (words.length === 0) return 'screen'
  return words.map((w) => w.toLowerCase()).join('_')
}

/** The stable, sanitized base name a widget's own identifiers key off — its tagId when set (so
 * generated names read naturally, e.g. `wifi_btn`) or its short id otherwise. widget.id is a
 * nanoid(), whose default alphabet includes '-' and '_' — not sanitizing the fallback path the
 * same way the tagId path already is produces an invalid C++ identifier (e.g. `w_WO0lX-`)
 * whenever a generated id happens to contain a '-' in its first few characters, breaking the
 * compile. Exported so the event-callback naming (collectEvents) can build a clean
 * `<base>_event_cb` name without carrying widgetVarName's own `_obj` suffix into it. */
export function widgetBaseName(widget: UiWidget): string {
  return widget.tagId ? toCIdentifier(widget.tagId) : toCIdentifier(`w_${widget.id.slice(0, 6)}`)
}

/** Local C++ variable name for a widget's `lv_obj_t*` — see widgetBaseName() above.
 * Exported for scriptLang/codegen.ts's CodegenContext (see buildCodegenContext below) — the
 * script codegen needs the exact same variable name this file's own widget-creation code uses. */
export function widgetVarName(widget: UiWidget): string {
  return `${widgetBaseName(widget)}_obj`
}

/** `Create<Name>[<Kind>]()` function name for a named (tagId-bearing) widget — appends the
 * widget kind (Button/Label/...) unless the id already reads as ending with it, so `id="wifi"`
 * (a button) becomes `CreateWifiButton` while `id="statusLabel"` (a label) becomes
 * `CreateStatusLabel` rather than the redundant `CreateStatusLabelLabel`. */
export function widgetCreateFnName(widget: UiWidget): string {
  const idPascal = toPascalCase(widget.tagId ?? widget.id)
  const kindPascal = toPascalCase(UI_WIDGET_LABELS[widget.type])
  const alreadyEndsWithKind = idPascal.toLowerCase().endsWith(kindPascal.toLowerCase())
  return `Create${idPascal}${alreadyEndsWithKind ? '' : kindPascal}`
}

export function screenCreateFnName(screenName: string): string {
  const pascal = toPascalCase(screenName)
  return pascal.toLowerCase().endsWith('screen') ? `Create${pascal}` : `Create${pascal}Screen`
}

export function screenShowFnName(screenName: string): string {
  const pascal = toPascalCase(screenName)
  return pascal.toLowerCase().endsWith('screen') ? `Show${pascal}` : `Show${pascal}Screen`
}

