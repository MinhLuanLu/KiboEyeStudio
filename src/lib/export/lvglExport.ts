/** Builds the naming/lookup context scriptLang/codegen.ts needs but can't own itself (it must
 * not import from this file — see the file-top comment on avoiding a circular dependency).
 * `identByAssetId`/`rules` come from the real, already-computed asset/style export so a
 * script's `setSource("logo.png")`/`.addClass("x")` resolve to the EXACT identifiers the rest
 * of this file generated — see buildValidationCodegenContext below for the lighter, synchronous
 * variant validateLvglExport.ts uses (no RGB565 decode needed just to validate). */
function buildCodegenContext(uiDesign: UiDesignProject, rules: CssRuleExport[], identByAssetId: Map<string, string>, ns: string): CodegenContext {
  return {
    widgets: uiDesign.widgets,
    varNameForWidget: widgetVarName,
    identForAssetName: (name) => {
      const asset = uiDesign.assets.find((a) => a.name === name)
      return asset ? identByAssetId.get(asset.id) : undefined
    },
    identForClassSelector: (className) => rules.find((r) => r.rule.selector === `.${className}`)?.ident,
    screenFnNameByName: (screenName) => {
      const screen = uiDesign.screens.find((s) => s.name === screenName)
      return screen ? screenShowFnName(screen.name) : undefined
    },
    identForVariableName: (name) => {
      const v = uiDesign.variables.find((v) => v.name === name)
      return v ? { getter: variableGetterName(v), setter: variableSetterName(v), type: uiVariableExprType(v.type) } : undefined
    },
    namespaceName: ns
  }
}

/** Synchronous sibling of buildCodegenContext for validateLvglExport.ts — asset "idents" here
 * are placeholder truthy strings (existence checks only, never emitted into real output), so
 * validating a script never has to pay for the async RGB565 asset decode a real export does. */
export function buildValidationCodegenContext(project: Project): CodegenContext {
  const uiDesign = project.uiDesign
  const widgets = allReachableWidgets(uiDesign)
  const rules = usedCssRules(uiDesign, widgets)
  return {
    widgets: uiDesign.widgets,
    varNameForWidget: widgetVarName,
    identForAssetName: (name) => (uiDesign.assets.some((a) => a.name === name) ? 'validated' : undefined),
    identForClassSelector: (className) => rules.find((r) => r.rule.selector === `.${className}`)?.ident,
    screenFnNameByName: (screenName) => (uiDesign.screens.some((s) => s.name === screenName) ? screenShowFnName(screenName) : undefined),
    identForVariableName: (name) => {
      const v = uiDesign.variables.find((v) => v.name === name)
      return v ? { getter: variableGetterName(v), setter: variableSetterName(v), type: uiVariableExprType(v.type) } : undefined
    },
    namespaceName: sanitizeIdentifier(project.name)
  }
}

const EMPTY_CODEGEN_RESULT: CodegenResult = {
  variables: [],
  functionPrototypes: [],
  functions: [],
  eventHandlers: [],
  timers: [],
  initStatements: [],
  hardwareStubs: [],
  updateBindingsFn: [],
  errors: []
}

function runScriptCodegen(uiDesign: UiDesignProject, ctx: CodegenContext): CodegenResult {
  if (!uiDesign.script.trim()) return EMPTY_CODEGEN_RESULT
  const parsed = parseScript(uiDesign.script)
  if (!parsed.program) return { ...EMPTY_CODEGEN_RESULT, errors: parsed.errors }
  return generateScriptCpp(parsed.program, uiDesign.script, ctx)
}

// ---------------------------------------------------------------------------------------------
// lv_conf.h — generated from LVGL 9.5.0's own real lv_conf_template.h (see lvConfTemplate.ts),
// not a hand-authored subset. Two edits are applied: (1) flip the "Content enable" #if 0 guard
// to #if 1 — LVGL ships the template disabled by default, and copying it without this flip is
// this export's single most common first compile failure; (2) turn on whichever built-in
// lv_font_montserrat_* sizes styleSetCalls() can ever reference (the fixed {12,14,16,18,20,24}
// set matching its font-size-selection ternary above), so any design using one compiles without
// a separate manual step. Every other setting is left at LVGL's own stock defaults on purpose —
// deviating further risks producing a different, more confusing error than the real template
// would. The two exceptions are LV_BUILD_EXAMPLES/LV_BUILD_DEMOS, turned off in the embedded
// template itself (not here) since this export never needs LVGL's own example/demo code.
// ---------------------------------------------------------------------------------------------

const MONTSERRAT_SIZES_ALWAYS_AVAILABLE = [12, 14, 16, 18, 20, 24]

function generateLvConf(): string {
  let conf = LV_CONF_TEMPLATE_V9.replace(
    '#if 0 /* Set this to "1" to enable content */',
    '#if 1 /* Set this to "1" to enable content */'
  )
  for (const size of MONTSERRAT_SIZES_ALWAYS_AVAILABLE) {
    conf = conf.replace(new RegExp(`(#define LV_FONT_MONTSERRAT_${size}\\s+)\\d`), '$11')
  }
  return `/*
 * lv_conf.h
 *
 * ${GENERATED_BY_LINE}
 *
 * This is LVGL ${LVGL_VERSION}'s own real lv_conf_template.h with its "Content enable" guard
 * flipped on and the lv_font_montserrat_* sizes this export can use already turned on — ready
 * to use as-is. See README.md's "Configuring lv_conf.h" section for where to place this file.
 *
 * You MAY edit this file for your own hardware (e.g. LV_COLOR_DEPTH if your display driver
 * expects something other than RGB565, LV_MEM_SIZE if you hit allocation failures, LV_USE_LOG
 * while bringing up your display driver) — unlike the other generated files, this one is meant
 * to be a starting point you own, not something re-export silently overwrites without you
 * noticing (re-exporting still regenerates it, so keep any manual edits in mind before you do).
 */
${conf}`
}

// ---------------------------------------------------------------------------------------------
// "UI Screen Only" export — a standalone, dependency-free .h/.cpp pair for ONE screen, safe to
// drop into any existing LVGL project. Deliberately NOT built on generateKiboUI()'s shared
// KiboUI:: namespace/registry/ShowScreen dispatcher (those are inherently project-wide concerns
// a single screen doesn't have) — uses the snake_case create_<screen>_screen()/
// show_<screen>_screen() free-function naming this mode's own spec asked for verbatim
// (deliberately different from the rest of this file's PascalCase `KiboUI::CreateXxxScreen()`
// convention, which "Complete Project" mode keeps unchanged — see the file-top note on why).
//
// Deliberately excludes the Logic tab's script entirely (not just cross-screen event handlers):
// codegen.ts's `timers`/`variables`/`functions`/`updateBindingsFn` output has no per-widget
// attribution (CodegenTimer and top-level declarations aren't tied to any widget/screen at all —
// only CodegenEventHandler carries a widgetId), so a partial include risks emitting a call to a
// variable/function/timer that doesn't exist in this standalone file — a compile break in
// exactly the kind of file this mode promises is dependency-free. Every widget on the screen
// instead gets the same empty `// TODO` event stub the exporter already uses for script-free
// widgets (collectEvents' fallback, called here with an empty scriptHandlers array) — real,
// working per-widget stubs, just not pre-filled with script-derived bodies. Export "Complete
// Project" for the real script-generated behavior.
// ---------------------------------------------------------------------------------------------

export interface UiScreenExportResult {
  files: LvglExportFile[]
  /** Non-fatal notes about what this mode deliberately leaves out (script) — surfaced in the
   * validation panel, not just buried in this file's own doc comments. */
  notes: string[]
}

/** Strips a redundant trailing "screen" (e.g. "Main Screen" or a user-typed "wifi_screen")
 * before the `_screen` suffix generateUiScreenExport always appends — mirrors
 * screenCreateFnName/screenShowFnName's identical dedup for the PascalCase naming "Complete
 * Project" mode uses, so "Main Screen" becomes create_main_screen() rather than the redundant
 * create_main_screen_screen(). Exported so LvglExportDialog.tsx can show the same derived
 * filename as a live preview next to the custom-name field, without duplicating this logic. */
export function deriveUiScreenSnakeName(name: string): string {
  const snakeRaw = toSnakeCase(name)
  return snakeRaw.replace(/_?screen$/, '') || snakeRaw
}

/** `customName`, when non-empty, overrides the screen's own name for filenames/function names
 * only (`create_<name>_screen()`/`show_<name>_screen()`, `<name>_screen.h/.cpp`) — doc comments
 * and USAGE.md still reference the screen's real name for semantic identity. Lets a user export
 * the same screen under a name of their choosing (e.g. "wifi_setup") instead of always getting
 * whatever the screen happens to be called in Kibo Eye Studio. */
export async function generateUiScreenExport(project: Project, screenId: string, customName?: string): Promise<UiScreenExportResult> {
  const uiDesign = project.uiDesign
  const screen = uiDesign.screens.find((s) => s.id === screenId)
  if (!screen) throw new Error(`Screen "${screenId}" not found.`)

  const widgets = reachableWidgetsForScreen(uiDesign, screen)
  const rules = usedCssRules(uiDesign, widgets)

  const snake = deriveUiScreenSnakeName(customName?.trim() || screen.name)
  const createFnName = `create_${snake}_screen`
  const showFnName = `show_${snake}_screen`
  const headerFilename = `${snake}_screen.h`
  const sourceFilename = `${snake}_screen.cpp`
  const assetsFilenameBase = `${snake}_screen_assets`
  const assetsHeaderFilename = `${assetsFilenameBase}.h`
  const assetsSourceFilename = `${assetsFilenameBase}.cpp`
  // No shared namespace exists in this standalone, single-file mode — a short, unbranded,
  // collision-free local prefix is enough (this function is only ever called once, from within
  // this same file). exportLvglStyles appends `_InitStyles` to whatever prefix it's given.
  const stylesNsPrefix = 'Ui'

  const { header: assetsHeaderRaw, source: assetsSourceRaw, identByAssetId } = await exportLvglAssets(uiDesign, widgets, rules, assetsFilenameBase)
  const stylesCode = exportLvglStyles(widgets, rules, identByAssetId, stylesNsPrefix)
  const events = collectEvents(widgets, [] /* no script output — see the section comment above */)

  const notes: string[] = []
  if (uiDesign.script.trim()) {
    notes.push(
      'This screen-only export uses empty `// TODO` event callback stubs — the Logic tab\'s script isn\'t included here, since it may reference other screens\' widgets, global timers, or variables that wouldn\'t exist in this standalone file. Export "Complete Project" for real script-generated behavior.'
    )
  }

  // ---- header ----
  const h: string[] = [
    `/*
 * ${headerFilename}
 *
 * ${GENERATED_BY_LINE} ("${screen.name}" screen only).
 *
 * Standalone, dependency-free: no LVGL/display/SPI/board initialization anywhere in this file
 * or its .cpp — call this from an existing LVGL project that already calls lv_init() and has a
 * display registered. Do NOT hand-edit — re-export instead.
 *
 * Required: LVGL ${LVGL_VERSION}, already initialized by your own project.
 *
 * Usage:
 *   #include "${headerFilename}"
 *   ${showFnName}();   // creates + loads this screen
 *
 * Finding a widget by its ID: this standalone mode deliberately has no Project_Register()/
 * FindWidget() registry (that's Complete Project export's own scaffolding — out of scope for a
 * single dependency-free screen file). If you gave a widget an ID in the Properties panel (e.g.
 * id="wifiButton"), its lv_obj_t* is a \`static\` variable named \`wifiButton_obj\` inside
 * ${sourceFilename} — declare \`extern lv_obj_t* wifiButton_obj;\` in your own .cpp to reference it
 * directly, or use ${snake}_focus_group()/lv_group_get_focused() below if you just need
 * "whichever widget is currently focused."
 */
#pragma once
#include "lvgl.h"

// Creates this screen's widget tree and returns the root lv_obj_t* (does NOT load it — see
// ${showFnName}() below for that).
lv_obj_t* ${createFnName}();

// Creates and loads this screen as the active LVGL screen, deleting whatever screen was active
// before.
void ${showFnName}();

// Returns this screen's LVGL focus group — every focusable widget on it (buttons, switches,
// sliders, checkboxes, dropdowns, rollers, text areas, list buttons, arcs, tabs, and any widget
// with a click/press/release handler) is added to it. Connect a keyboard or rotary encoder input
// device to it via lv_indev_set_group() for real hardware focus navigation.
lv_group_t* ${snake}_focus_group();
`
  ]

  // ---- source ----
  const c: string[] = [
    `/*
 * ${sourceFilename}
 *
 * ${GENERATED_BY_LINE} ("${screen.name}" screen only).
 * The exception is the \`// TODO\` callback bodies below,
 * which are safe to fill in (a re-export preserves the stub declarations, not any body you've
 * typed into one — move logic you want to keep into your own file instead).
 */
#include "${headerFilename}"`
  ]
  if (identByAssetId.size > 0) c.push(`#include "${assetsHeaderFilename}"`)
  c.push('')
  c.push(stylesCode)
  c.push('')

  c.push('// ---- Focus group — every focusable widget on this screen is added to it (see the')
  c.push('// per-widget lv_group_add_obj() calls below). ----')
  c.push('static lv_group_t* s_focusGroup = nullptr;')
  c.push('')
  c.push(`lv_group_t* ${snake}_focus_group() { return s_focusGroup; }`)
  c.push('')

  if (widgets.length > 0) {
    c.push('// ---- Widget objects — one `static lv_obj_t*` per widget, named after its Properties-panel')
    c.push('// ID when it has one (e.g. id="wifiButton" -> wifiButton_obj). No Project_Register()/')
    c.push('// FindWidget() lookup-by-string exists in this standalone mode (that\'s Complete Project')
    c.push('// export\'s own scaffolding) — to reach one of these from your own .cpp, declare a matching')
    c.push('// `extern lv_obj_t* wifiButton_obj;` instead. ----')
    const declared = new Set<string>()
    for (const w of widgets) {
      const v = widgetVarName(w)
      if (!declared.has(v)) {
        declared.add(v)
        c.push(`static lv_obj_t* ${v} = nullptr;`)
      }
      if (w.type === 'button') c.push(`static lv_obj_t* ${v}_label = nullptr;`)
    }
    c.push('')
  }

  const eventByWidgetId = new Map<string, EventExport>(events.map((ev) => [ev.widget.id, ev]))
  if (events.length > 0) {
    c.push('// ---- Event Callbacks — fill in the switch cases (inside the USER CODE markers) with your own logic. ----')
    for (const ev of events) {
      c.push(...emitEventCallbackBody(ev, true))
      c.push('')
    }
  }

  // Named-widget sub-functions + the main create function — mirrors generateKiboUI's emitWidget
  // recursion, but writes into one flat file (no separate registry/lookup mechanism needed,
  // since nothing outside this file ever references these widgets by id).
  const namedFnBuffers: string[][] = []
  const emittedFnNames = new Set<string>([createFnName, showFnName])
  const uniqueFnName = (base: string): string => {
    if (!emittedFnNames.has(base)) {
      emittedFnNames.add(base)
      return base
    }
    let i = 2
    while (emittedFnNames.has(`${base}${i}`)) i++
    emittedFnNames.add(`${base}${i}`)
    return `${base}${i}`
  }
  const emitWidget = (widget: UiWidget, parentVar: string, buffer: string[], indent: string) => {
    const varName = widgetVarName(widget)
    const ev = eventByWidgetId.get(widget.id)
    const isFocusable = EVENT_CAPABLE_WIDGET_TYPES.has(widget.type) || !!ev
    if (widget.tagId) {
      const fnName = uniqueFnName(widgetCreateFnName(widget))
      const fnBuffer: string[] = []
      fnBuffer.push(...widgetCreateCalls(widget, varName, 'parent', identByAssetId, '  '))
      if (isFocusable) fnBuffer.push(`  lv_obj_add_style(${varName}, &s_focusedStyle, LV_PART_MAIN | LV_STATE_FOCUSED);`)
      fnBuffer.push(...styleApplyCalls(widget, rules, varName, '  '))
      if (ev) fnBuffer.push(`  lv_obj_add_event_cb(${varName}, ${ev.handlerName}, LV_EVENT_ALL, NULL);`)
      // Deliberately no lv_group_focus_obj() call here — leaving the group without an initial
      // focus means no widget shows the focused-style border on screen load; LVGL's own
      // lv_group_focus_next()/prev() already fall back to the group's first object the moment the
      // user actually turns the encoder, so the focus outline only ever appears once real encoder
      // input starts, not by default.
      if (isFocusable) fnBuffer.push(`  lv_group_add_obj(s_focusGroup, ${varName});`)
      for (const child of children(uiDesign, widget)) emitWidget(child, varName, fnBuffer, '  ')
      fnBuffer.push(`  return ${varName};`)
      namedFnBuffers.push([`static lv_obj_t* ${fnName}(lv_obj_t* parent) {`, ...fnBuffer, '}'])
      buffer.push(`${indent}${fnName}(${parentVar});`)
    } else {
      buffer.push(...widgetCreateCalls(widget, varName, parentVar, identByAssetId, indent))
      if (isFocusable) buffer.push(`${indent}lv_obj_add_style(${varName}, &s_focusedStyle, LV_PART_MAIN | LV_STATE_FOCUSED);`)
      buffer.push(...styleApplyCalls(widget, rules, varName, indent))
      if (ev) buffer.push(`${indent}lv_obj_add_event_cb(${varName}, ${ev.handlerName}, LV_EVENT_ALL, NULL);`)
      if (isFocusable) buffer.push(`${indent}lv_group_add_obj(s_focusGroup, ${varName});`)
      for (const child of children(uiDesign, widget)) emitWidget(child, varName, buffer, indent)
    }
  }

  const rootWidget = uiDesign.widgets[screen.rootWidgetId]
  const bodyBuffer: string[] = []
  if (rootWidget) {
    for (const child of children(uiDesign, rootWidget)) emitWidget(child, 'screen', bodyBuffer, '  ')
  }

  if (namedFnBuffers.length > 0) {
    c.push('// ---- Named widget builders ----')
    for (const fn of namedFnBuffers) {
      c.push(fn.join('\n'))
      c.push('')
    }
  }

  c.push(`lv_obj_t* ${createFnName}() {`)
  c.push('  static bool s_stylesInited = false;')
  c.push('  if (!s_stylesInited) { s_stylesInited = true; Ui_InitStyles(); }')
  c.push('  if (s_focusGroup == nullptr) { s_focusGroup = lv_group_create(); }')
  // LVGL's own lv_group_add_obj() auto-focuses an object the moment it's the first one added to
  // an empty group (a built-in library behavior, not something this file controls) — freezing the
  // group while the widgets below are created suppresses that, so nothing shows the focused-style
  // border until the user's first real encoder/keyboard input.
  c.push('  lv_group_focus_freeze(s_focusGroup, true);')
  c.push('  lv_obj_t* screen = lv_obj_create(NULL);')
  c.push(...bodyBuffer)
  c.push('  lv_group_focus_freeze(s_focusGroup, false);')
  c.push('  return screen;')
  c.push('}')
  c.push('')
  c.push(`void ${showFnName}() {`)
  c.push(`  lv_obj_t* screen = ${createFnName}();`)
  c.push('  lv_obj_t* old_screen = lv_screen_active();')
  c.push('  lv_screen_load(screen);')
  c.push('  lv_refr_now(NULL);')
  c.push('  if (old_screen != NULL && old_screen != screen) {')
  c.push('    lv_obj_delete(old_screen);')
  c.push('  }')
  c.push('}')
  c.push('')

  const files: LvglExportFile[] = [
    { name: headerFilename, content: h.join('\n') },
    { name: sourceFilename, content: c.join('\n') }
  ]
  if (identByAssetId.size > 0) {
    files.push({ name: assetsHeaderFilename, content: assetsHeaderRaw })
    files.push({ name: assetsSourceFilename, content: assetsSourceRaw })
  }
  const exampleWidgetId = namedWidgets(widgets)[0]?.tagId ?? null
  files.push({ name: 'USAGE.md', content: generateUsageMd(project, screen, snake, createFnName, showFnName, identByAssetId.size > 0, notes, exampleWidgetId) })

  return { files, notes }
}

function generateUsageMd(project: Project, screen: UiScreen, snake: string, createFnName: string, showFnName: string, hasAssets: boolean, notes: string[], exampleWidgetId: string | null): string {
  return `# ${screen.name} — Standalone LVGL Screen

"UI Screen Only" export from project "${project.name}". This is just this one screen — no LVGL/display/SPI/board initialization
anywhere in \`${snake}_screen.h\`/\`${snake}_screen.cpp\`${hasAssets ? `/\`${snake}_screen_assets.*\`` : ''}.
Drop these file(s) into any existing LVGL ${LVGL_VERSION} project that already calls \`lv_init()\`
and has a display registered.

## Usage

\`\`\`cpp
#include "${snake}_screen.h"

void setup() {
  // ... your existing lv_init() / display registration ...

  ${showFnName}();   // creates and shows this screen
}
\`\`\`

Call \`${createFnName}()\` instead of \`${showFnName}()\` if you want to build the screen without
immediately showing it (e.g. to pre-create it at startup and show it later).

## Event callbacks

Every interactive widget on this screen got an empty \`// TODO\` callback stub in
\`${snake}_screen.cpp\` — fill those in with your own logic. From anywhere else in your code, you
can trigger the same callback manually (as if a touch/mouse/keyboard/encoder had produced it) with
\`lv_obj_send_event()\`:

\`\`\`cpp
${exampleWidgetId ? `lv_obj_send_event(${toCIdentifier(exampleWidgetId)}_obj, LV_EVENT_CLICKED, nullptr);` : '// (no named widget on this screen yet — give one an ID in the Properties panel to reference it here)'}
lv_obj_send_event(${exampleWidgetId ? `${toCIdentifier(exampleWidgetId)}_obj` : 'someWidget_obj'}, LV_EVENT_PRESSED, nullptr);
lv_obj_send_event(${exampleWidgetId ? `${toCIdentifier(exampleWidgetId)}_obj` : 'someWidget_obj'}, LV_EVENT_RELEASED, nullptr);
lv_obj_send_event(${exampleWidgetId ? `${toCIdentifier(exampleWidgetId)}_obj` : 'someWidget_obj'}, LV_EVENT_VALUE_CHANGED, nullptr);
\`\`\`

(This screen's widget variables — e.g. \`${exampleWidgetId ? `${toCIdentifier(exampleWidgetId)}_obj` : 'wifiButton_obj'}\` — are \`static\` to \`${snake}_screen.cpp\`; reference
them from your own \`.cpp\` file by adding your own \`extern\` declaration, or call
\`lv_group_get_focused(${snake}_focus_group())\` if you just need "whatever's focused right now".)

## Focus (keyboard / rotary encoder / physical buttons)

Every focusable widget (buttons, switches, sliders, checkboxes, dropdowns, rollers, text areas,
list buttons, arcs, tabs, and any widget with a click/press/release handler) is automatically
added to this screen's own LVGL focus group and gets a visible border (\`LV_STATE_FOCUSED\`) while
focused — nothing is focused by default when the screen is created, so no border shows up until
the user actually starts navigating; the first real encoder/keyboard input then focuses the
group's first widget automatically (standard LVGL group behavior). Connect a keyboard or rotary
encoder input device to it so hardware input can move focus:

\`\`\`cpp
lv_indev_t* encoderIndev = /* your registered LVGL encoder input device */;
if (encoderIndev != nullptr) {
  lv_indev_set_group(encoderIndev, ${snake}_focus_group());
}
\`\`\`

Rotating the encoder moves focus between widgets; pressing it activates whichever widget is
currently focused (LVGL generates \`LV_EVENT_CLICKED\` for you). You can also move focus from code:

\`\`\`cpp
lv_group_focus_next(${snake}_focus_group());   // move to the next focusable widget
lv_group_focus_prev(${snake}_focus_group());   // move to the previous focusable widget
${exampleWidgetId ? `lv_group_focus_obj(${toCIdentifier(exampleWidgetId)}_obj);         // give one specific widget real keyboard/encoder focus` : '// lv_group_focus_obj(someWidget_obj);   // give one specific widget real keyboard/encoder focus'}
\`\`\`

\`lv_group_focus_obj()\` gives a widget real LVGL keyboard/encoder focus (the group's current
selection). \`lv_obj_add_state(obj, LV_STATE_FOCUSED)\`/\`lv_obj_remove_state(obj, LV_STATE_FOCUSED)\`
only change that widget's *visual* focused appearance without touching the group's selection — use
those only if you want the focused look without real input-device focus.
${notes.length > 0 ? `\n## Notes\n\n${notes.map((n) => `- ${n}`).join('\n')}\n` : ''}`
}

/** The "LVGL Code" tab's live, always-in-sync view of one screen — deliberately NOT one of the
 * downloadable export modes above (no files, no zip): a single readable code string meant to be
 * regenerated on every edit and read on screen, matching the same "single simple file, no
 * namespace ceremony" shape `generateUiScreenExport` already produces for its standalone mode,
 * with two differences suited to a live learning view rather than a download:
 *  1. Real script-compiled event bodies (via runScriptCodegen/collectEvents, exactly like
 *     "Complete Project" mode) instead of empty `// TODO` stubs — wiring up an event in the
 *     Properties panel or Logic tab should visibly produce real code here, not a stub.
 *  2. No image pixel data — embedding a multi-hundred-line PROGMEM byte array on every keystroke
 *     would swamp the "clean, readable, beginner code" this view exists for; a short comment
 *     marks where the real bytes go (see the Export dialog for those). Every other primitive
 *     (widgetCreateCalls/styleApplyCalls/exportLvglStyles/the named-widget-builder recursion) is
 *     reused verbatim from generateUiScreenExport's own body, not reimplemented. Entirely
 *     synchronous (no asset decode) so callers can call this directly on every render/store
 *     change with no debounce needed, the same way HtmlEditor/CssEditor's live text already
 *     works. */
export function generateLiveScreenCode(project: Project, screenId: string | null): string {
  const uiDesign = project.uiDesign
  const screen = uiDesign.screens.find((s) => s.id === screenId) ?? uiDesign.screens[0]
  if (!screen) return '// Add a screen in UI/UX Design Mode to see its generated LVGL code here.'

  const widgets = reachableWidgetsForScreen(uiDesign, screen)
  const rules = usedCssRules(uiDesign, widgets)
  const assets = usedAssets(uiDesign, widgets, rules)
  // Identifiers only — no decode (see the doc comment above). Real byte arrays are only ever
  // produced by the actual Export dialog, which does need them.
  const identByAssetId = new Map<string, string>(assets.map((a, i) => [a.id, assetIdent(a, i)]))

  const snake = deriveUiScreenSnakeName(screen.name)
  const createFnName = `create_${snake}_screen`
  const showFnName = `show_${snake}_screen`
  const stylesNsPrefix = 'Ui'

  const stylesCode = exportLvglStyles(widgets, rules, identByAssetId, stylesNsPrefix)
  const codegen = runScriptCodegen(uiDesign, buildCodegenContext(uiDesign, rules, identByAssetId, stylesNsPrefix))
  const events = collectEvents(widgets, codegen.eventHandlers)

  const out: string[] = [
    `// ${screen.name} — live LVGL ${LVGL_VERSION} preview, regenerated automatically as you design.`,
    '// This is a simplified, readable view for learning — open the Export dialog for the real,',
    '// downloadable project (with embedded images and full board/display setup).',
    ''
  ]
  if (codegen.errors.length > 0) {
    out.push(`// Note: ${codegen.errors.length} issue(s) in the Logic tab's script couldn't be converted — see its validation panel. Event bodies below fall back to TODO stubs where affected.`)
    out.push('')
  }
  if (assets.length > 0) {
    out.push(`// Image assets used here (${assets.map((a) => a.name).join(', ')}) are embedded as real`)
    out.push('// pixel data only in the actual export — see the Export dialog.')
    out.push('')
  }

  out.push(stylesCode)
  out.push('')

  out.push('// ---- Focus group — every focusable widget on this screen is added to it ----')
  out.push('static lv_group_t* s_focusGroup = nullptr;')
  out.push('')

  if (widgets.length > 0) {
    out.push('// ---- Widget objects ----')
    const declared = new Set<string>()
    for (const w of widgets) {
      const v = widgetVarName(w)
      if (!declared.has(v)) {
        declared.add(v)
        out.push(`static lv_obj_t* ${v} = nullptr;`)
      }
      if (w.type === 'button') out.push(`static lv_obj_t* ${v}_label = nullptr;`)
    }
    out.push('')
  }

  const eventByWidgetId = new Map<string, EventExport>(events.map((ev) => [ev.widget.id, ev]))
  if (events.length > 0) {
    out.push('// ---- Event Callbacks ----')
    for (const ev of events) {
      out.push(...emitEventCallbackBody(ev, false))
      out.push('')
    }
  }

  // Same named-widget-builder recursion as generateUiScreenExport — see that function's own
  // comment for why this stays one flat file rather than a per-widget-function file split.
  const namedFnBuffers: string[][] = []
  const emittedFnNames = new Set<string>([createFnName, showFnName])
  const uniqueFnName = (base: string): string => {
    if (!emittedFnNames.has(base)) {
      emittedFnNames.add(base)
      return base
    }
    let i = 2
    while (emittedFnNames.has(`${base}${i}`)) i++
    emittedFnNames.add(`${base}${i}`)
    return `${base}${i}`
  }
  const emitWidget = (widget: UiWidget, parentVar: string, buffer: string[], indent: string) => {
    const varName = widgetVarName(widget)
    const ev = eventByWidgetId.get(widget.id)
    const isFocusable = EVENT_CAPABLE_WIDGET_TYPES.has(widget.type) || !!ev
    if (widget.tagId) {
      const fnName = uniqueFnName(widgetCreateFnName(widget))
      const fnBuffer: string[] = []
      fnBuffer.push(...widgetCreateCalls(widget, varName, 'parent', identByAssetId, '  '))
      if (isFocusable) fnBuffer.push(`  lv_obj_add_style(${varName}, &s_focusedStyle, LV_PART_MAIN | LV_STATE_FOCUSED);`)
      fnBuffer.push(...styleApplyCalls(widget, rules, varName, '  '))
      if (ev) fnBuffer.push(`  lv_obj_add_event_cb(${varName}, ${ev.handlerName}, LV_EVENT_ALL, NULL);`)
      // Deliberately no lv_group_focus_obj() call here — leaving the group without an initial
      // focus means no widget shows the focused-style border on screen load; LVGL's own
      // lv_group_focus_next()/prev() already fall back to the group's first object the moment the
      // user actually turns the encoder, so the focus outline only ever appears once real encoder
      // input starts, not by default.
      if (isFocusable) fnBuffer.push(`  lv_group_add_obj(s_focusGroup, ${varName});`)
      for (const child of children(uiDesign, widget)) emitWidget(child, varName, fnBuffer, '  ')
      fnBuffer.push(`  return ${varName};`)
      namedFnBuffers.push([`static lv_obj_t* ${fnName}(lv_obj_t* parent) {`, ...fnBuffer, '}'])
      buffer.push(`${indent}${fnName}(${parentVar});`)
    } else {
      buffer.push(...widgetCreateCalls(widget, varName, parentVar, identByAssetId, indent))
      if (isFocusable) buffer.push(`${indent}lv_obj_add_style(${varName}, &s_focusedStyle, LV_PART_MAIN | LV_STATE_FOCUSED);`)
      buffer.push(...styleApplyCalls(widget, rules, varName, indent))
      if (ev) buffer.push(`${indent}lv_obj_add_event_cb(${varName}, ${ev.handlerName}, LV_EVENT_ALL, NULL);`)
      if (isFocusable) buffer.push(`${indent}lv_group_add_obj(s_focusGroup, ${varName});`)
      for (const child of children(uiDesign, widget)) emitWidget(child, varName, buffer, indent)
    }
  }

  const rootWidget = uiDesign.widgets[screen.rootWidgetId]
  const bodyBuffer: string[] = []
  if (rootWidget) {
    for (const child of children(uiDesign, rootWidget)) emitWidget(child, 'screen', bodyBuffer, '  ')
  }

  if (namedFnBuffers.length > 0) {
    out.push('// ---- Named widget builders ----')
    for (const fn of namedFnBuffers) {
      out.push(fn.join('\n'))
      out.push('')
    }
  }

  out.push(`lv_obj_t* ${createFnName}() {`)
  out.push('  static bool s_stylesInited = false;')
  out.push('  if (!s_stylesInited) { s_stylesInited = true; Ui_InitStyles(); }')
  out.push('  if (s_focusGroup == nullptr) { s_focusGroup = lv_group_create(); }')
  // LVGL's own lv_group_add_obj() auto-focuses an object the moment it's the first one added to
  // an empty group (a built-in library behavior, not something this file controls) — freezing the
  // group while the widgets below are created suppresses that, so nothing shows the focused-style
  // border until the user's first real encoder/keyboard input.
  out.push('  lv_group_focus_freeze(s_focusGroup, true);')
  out.push('  lv_obj_t* screen = lv_obj_create(NULL);')
  out.push(...bodyBuffer)
  out.push('  lv_group_focus_freeze(s_focusGroup, false);')
  out.push('  return screen;')
  out.push('}')
  out.push('')
  out.push(`void ${showFnName}() {`)
  out.push(`  lv_obj_t* screen = ${createFnName}();`)
  out.push('  lv_obj_t* old_screen = lv_screen_active();')
  out.push('  lv_screen_load(screen);')
  out.push('  lv_refr_now(NULL);')
  out.push('  if (old_screen != NULL && old_screen != screen) {')
  out.push('    lv_obj_delete(old_screen);')
  out.push('  }')
  out.push('}')

  return out.join('\n')
}

/** Assembles the final ui.cpp: one shared file-header comment + one shared #include block,
 * followed by `cppBody` (styles + registry/scaffolding + every screen's creation code, already
 * joined with section banners by generateKiboUIParts) — B2's file-consolidation goal folds what
 * used to be UIStyles.h/UICore.h/one-file-per-screen into this single file instead. */
function generateUiCpp(cppBody: string, hasAssets: boolean): string {
  // ui.cpp is a plain .cpp translation unit, not a .ino sketch — the Arduino core's implicit
  // `Serial` global (and Arduino.h itself) is only auto-included for .ino files, so any
  // Serial.* call reaching this file (a hardware stub, or a hand-typed USER CODE body) needs the
  // include added explicitly here or it won't compile. Checked once against the whole assembled
  // body rather than threaded through every generator that could possibly emit a Serial.* call.
  const needsArduino = cppBody.includes('Serial.')
  const lines = [
    `/*
 * ui.cpp
 *
 * ${GENERATED_BY_LINE} ("Complete Project" export).
 * Styles, widget registry/scaffolding, and every screen's creation code, in that order (see the
 * section banners below) — do NOT hand-edit; re-export instead. The exception is any
 * \`// TODO\` event-callback body, which is safe to fill in.
 */
#include "ui.h"
${hasAssets ? '#include "assets.h"\n' : ''}${needsArduino ? '#include <Arduino.h> // for Serial — used by a callback/USER CODE body below\n' : ''}#include <string.h>
`
  ]
  lines.push(cppBody)
  lines.push('')
  return lines.join('\n')
}

// Arduino sketches do NOT auto-recurse into a `src/` subfolder the way libraries do — a plain
// `.ino` only ever sees files sitting directly next to it, so `src/ui.h` etc. would silently
// fail to resolve, leaving `#include "ui.h"` unable to find anything and every `${ns}::*` call
// in the sketch un-declared (confirmed by a real compile attempt — this was a bug in an earlier
// version of this exporter, not a theoretical concern). PlatformIO's `src/` handling is genuinely
// reliable (it always compiles everything under `src/` and adds `src/`/`include/` to the search
// path), so PlatformIO format keeps the nested `src/{components,screens,assets}` layout; Arduino
// format instead gets everything flattened into one directory next to the entry sketch (plain
// headers, no subfolders, compiled as one translation unit via #include). Every `#include "..."`
// with a `../`, `components/`, `screens/`, or `assets/` prefix is rewritten to a bare filename —
// safe because every one of those paths was only ever pointing at another file in this same
// export (never a real external path), and `usedScreenFilenames` above is already seeded with
// the shared component/asset basenames so flattening can't introduce a same-name collision.
function flattenForArduino(files: LvglExportFile[]): LvglExportFile[] {
  const includeRewrite = /#include "((?:\.\.\/)?(?:components\/|screens\/|assets\/)?)([^"]+)"/g
  // Cosmetic-only: the doc-comment prose inside each generated file (not the #include lines
  // themselves, already handled above) still says "src/ui.cpp"/"src/screens/*.h"/etc. — tidy
  // those up too so a reader of the flattened output isn't told to look in a src/ folder that
  // doesn't exist in this format.
  const proseRewrite: [RegExp | string, string][] = [
    [/\bsrc\/ui\.cpp\b/g, 'ui.cpp'],
    [/\bsrc\/screens\/\*\.h\b/g, 'the per-screen .h files'],
    [/\bcomponents\/(UICore\.h|UIStyles\.h)\b/g, '$1']
  ]
  return files.map((f) => {
    let content = f.content.replace(includeRewrite, '#include "$2"')
    for (const [pattern, replacement] of proseRewrite) content = content.replace(pattern, replacement)
    return { name: f.name.startsWith('src/') ? f.name.slice('src/'.length).split('/').pop()! : f.name, content }
  })
}

/** "Complete Project" mode's entry point — async because asset RGB565 decoding needs the
 * browser's canvas APIs. Reads only `project.uiDesign` (see the file-top comment) plus the
 * export-time `target` config (board/display/pins/format — never read from or written to the
 * project, see exportTarget.ts). Builds a nested `src/{ui.h,ui.cpp, components/*, screens/*,
 * assets/*}` layout (+ `include/UIConfig.h`/`include/lv_conf.h` + `platformio.ini`) for
 * PlatformIO, then — for Arduino format — flattens everything into one directory next to the
 * project-named `.ino` entry sketch via flattenForArduino(), since a plain Arduino sketch (as
 * opposed to a library) never recurses into a `src/` subfolder; `README.md`/`libraries.txt` are
 * generated last, after the format is known. The exported namespace/identifiers/filenames are
 * all derived from the project's own name (see naming.ts) — nothing here hardcodes this app's
 * own name into the output. */
/** Everything "Complete Project"/"Module"/"Header" modes share: widget/style/asset/script codegen
 * (identical regardless of board/pins/format, which only affect the entry sketch/config.h/
 * lv_conf.h — see generateLvglExport) assembled into ui.h/ui.cpp's parts. Extracted so the three
 * modes stay a "filtered/folded view of the same generator output," per the export feature's own
 * design, rather than three copies of this setup that could quietly drift apart. */
async function buildKiboUiCore(project: Project) {
  const uiDesign = project.uiDesign
  const ns = sanitizeIdentifier(project.name)
  const widgets = allReachableWidgets(uiDesign)
  const rules = usedCssRules(uiDesign, widgets)
  const { header: assetsHeader, source: assetsSource, identByAssetId } = await exportLvglAssets(uiDesign, widgets, rules, 'assets')
  const hasAssets = identByAssetId.size > 0
  // Fixed "Project" prefix (not the project-derived `ns`) for the style-init function — this is
  // internal scaffolding, not part of the branded public API, so it stays a stable generic name
  // (`Project_InitStyles`) regardless of the project's name — see Project_Register below for the
  // same reasoning applied to the widget registry.
  const stylesCode = exportLvglStyles(widgets, rules, identByAssetId, 'Project')
  const codegen = runScriptCodegen(uiDesign, buildCodegenContext(uiDesign, rules, identByAssetId, ns))
  const events = collectEvents(widgets, codegen.eventHandlers)
  const named = namedWidgets(widgets)
  const parts = generateKiboUIParts(uiDesign, widgets, rules, identByAssetId, events, stylesCode, codegen, ns)
  return { uiDesign, ns, widgets, rules, assetsHeader, assetsSource, identByAssetId, hasAssets, stylesCode, codegen, events, named, parts }
}

export async function generateLvglExport(project: Project, target: ExportTarget): Promise<LvglExportFile[]> {
  const { uiDesign, ns, widgets, rules, assetsHeader, assetsSource, hasAssets, codegen, events, named, parts } = await buildKiboUiCore(project)

  const config = generateKiboUIConfig(uiDesign.display, target, ns)
  const lvConf = generateLvConf()
  const mainShowFnName = uiDesign.screens[0] ? screenShowFnName(uiDesign.screens[0].name) : null
  const entryBaseName = sanitizeFilename(project.name)
  const entryFilename = target.format === 'arduino' ? `${entryBaseName}.ino` : 'src/main.cpp'
  const exampleWidgetId = named[0]?.tagId ?? null
  const mainEntry = generateMainEntry(mainShowFnName, target, entryFilename.replace(/^src\//, ''), ns, exampleWidgetId)
  const readme = generateReadme(project, widgets, rules, events, codegen, target, ns, exampleWidgetId)

  const configPath = target.format === 'arduino' ? 'config.h' : 'include/config.h'
  const lvConfPath = target.format === 'arduino' ? 'lv_conf.h' : 'include/lv_conf.h'
  // Sits directly alongside ui.h/ui.cpp (no separate assets/ subfolder needed now that it's just
  // one header+source pair) — the `src/` prefix is stripped by flattenForArduino below, same as
  // ui.h/ui.cpp's own.
  const assetsBase = 'src/assets'

  // B2's file-consolidation goal: a small, human-readable set of files rather than one per
  // screen/component — ui.h + ui.cpp (styles/registry/screens all folded in, see
  // generateKiboUIParts/generateUiCpp), assets only when the design actually has any, config.h
  // (the one file a user is expected to hand-edit for their own board), lv_conf.h, README.md.
  const files: LvglExportFile[] = [
    { name: entryFilename, content: mainEntry },
    { name: 'src/ui.h', content: parts.publicHeader },
    { name: 'src/ui.cpp', content: generateUiCpp(parts.cppBody, hasAssets) }
  ]
  if (hasAssets) {
    files.push({ name: `${assetsBase}.h`, content: assetsHeader }, { name: `${assetsBase}.cpp`, content: assetsSource })
  }
  files.push({ name: configPath, content: config }, { name: lvConfPath, content: lvConf }, { name: 'README.md', content: readme })
  if (target.format === 'platformio') {
    files.push({ name: 'platformio.ini', content: generatePlatformioIni(target) }, { name: 'libraries.txt', content: generateLibrariesTxt(target) })
  }

  return target.format === 'arduino' ? flattenForArduino(files) : files
}

/** "Module" mode — the exact same widget/style/asset/script codegen as "Complete Project"
 * (`generateLvglExport`/`buildKiboUiCore`), minus the entry sketch, `config.h`, and `lv_conf.h` —
 * for dropping `ui.h`/`ui.cpp`(/`assets.h`/`.cpp`) into an existing sketch that already calls
 * `lv_init()` and has a display registered. A filtered view of the same generator output, not a
 * separate generator — board/pins/format never affect ui.h/ui.cpp's content in the first place
 * (only the now-omitted entry sketch/config.h read `target`). */
export async function generateModuleExport(project: Project): Promise<LvglExportFile[]> {
  const { assetsHeader, assetsSource, hasAssets, parts } = await buildKiboUiCore(project)
  const files: LvglExportFile[] = [
    { name: 'ui.h', content: parts.publicHeader },
    { name: 'ui.cpp', content: generateUiCpp(parts.cppBody, hasAssets) }
  ]
  if (hasAssets) files.push({ name: 'assets.h', content: assetsHeader }, { name: 'assets.cpp', content: assetsSource })
  return files
}

/** "Header" mode — Module mode's `ui.h`/`ui.cpp`(/`assets.h`/`.cpp`) folded into a single file,
 * for small projects that want the absolute minimum to drop in. Pure text concatenation of the
 * same generated content Module mode uses (duplicate `#pragma once`/`#include "lvgl.h"` lines are
 * harmless — the preprocessor treats repeats as no-ops — so this doesn't need its own codegen). */
export async function generateHeaderExport(project: Project): Promise<LvglExportFile[]> {
  const { assetsHeader, assetsSource, hasAssets, parts } = await buildKiboUiCore(project)
  const uiCppContent = generateUiCpp(parts.cppBody, hasAssets)
  const pieces: { label: string; content: string }[] = [
    { label: 'Public API (ui.h)', content: parts.publicHeader },
    { label: 'Implementation (ui.cpp)', content: uiCppContent }
  ]
  if (hasAssets) pieces.push({ label: 'Image assets (assets.h/.cpp)', content: `${assetsHeader}\n\n${assetsSource}` })

  // Lines that would otherwise appear once per piece — cross-file includes that no longer point
  // anywhere useful once everything lives in one file, plus directives safe to only emit once at
  // the top (repeating them again below is harmless, but noisy).
  const SKIP_LINES = new Set(['#pragma once', '#include "lvgl.h"', '#include "ui.h"', '#include "assets.h"', '#include <string.h>'])
  const out: string[] = [
    `/*
 * ui.h
 *
 * ${GENERATED_BY_LINE} ("Header" export — the whole project folded into one file for easy
 * drop-in use; see "Module" or "Complete Project" mode for a multi-file version.)
 * Standalone: no LVGL/display/SPI/board initialization anywhere in this file — call this from an
 * existing LVGL project that already calls lv_init() and has a display registered. Do NOT
 * hand-edit — re-export instead; the exception is any USER CODE block (see the callback bodies
 * below), which a re-export preserves via the "Restore custom code" file-drop.
 */`,
    '#pragma once',
    '#include "lvgl.h"',
    '#include <string.h>',
    ''
  ]
  for (const piece of pieces) {
    out.push(`// =============================================================================================`)
    out.push(`// ---- ${piece.label} ----`)
    out.push(`// =============================================================================================`)
    out.push('')
    for (const line of piece.content.split('\n')) {
      if (SKIP_LINES.has(line.trim())) continue
      out.push(line)
    }
    out.push('')
  }
  return [{ name: 'ui.h', content: out.join('\n') }]
}

