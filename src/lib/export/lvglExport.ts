function generateKiboUIConfig(display: UiDisplaySettings, target: ExportTarget, ns: string): string {
  const macroPrefix = macroPrefixFor(ns)
  const pinLine = (macro: string, value: number): string => (value >= 0 ? `#define ${macro} ${value}` : `// #define ${macro} -1  // EDIT ME`)
  return `/*
 * config.h
 *
 * ${GENERATED_BY_LINE}
 *
 * This file contains editable hardware/display settings — pins/resolution come from the board
 * and display model chosen in the Export dialog. You SHOULD edit this file for your own board —
 * nothing else in this export needs manual edits (see ui.h's header comment).
 *
 * Required: ESP32 Arduino Core, LVGL ${LVGL_VERSION}, a supported display driver.
 */
#pragma once

// Display resolution/shape — from the board/display model chosen in the Export dialog.
// Edit these ONLY if your physical panel differs from what you selected there.
#define ${macroPrefix}_DISPLAY_WIDTH  ${Math.round(target.width)}
#define ${macroPrefix}_DISPLAY_HEIGHT ${Math.round(target.height)}
#define ${macroPrefix}_DISPLAY_ORIENTATION_${display.orientation.toUpperCase()} 1

${
  target.shape === 'round'
    ? `// This design targets a round display — LVGL widgets are clipped to the visible circle in\n// the studio preview; make sure your display driver reports a matching circular/round panel\n// if it has round-aware behavior (e.g. lv_display_set_antialiasing, round-display chroma tricks).\n#define ${macroPrefix}_DISPLAY_ROUND 1`
    : `// #define ${macroPrefix}_DISPLAY_ROUND 1  // uncomment if you switch to a round panel`
}

// Firmware/driver presentation rotation, set in the Display Settings panel — this does NOT
// change widget coordinates (those are always authored directly in Width x Height above as the
// logical resolution); it only tells your display driver which physical direction to present
// that logical resolution in, if your driver supports software rotation.
#define ${macroPrefix}_DISPLAY_ROTATION ${display.rotation}

// Matches this project's RGB565 color pipeline — change only if your display driver uses a
// different LV_COLOR_DEPTH (also update lv_conf.h's LV_COLOR_DEPTH to match, see README.md).
#define ${macroPrefix}_LVGL_COLOR_DEPTH 16

// Number of horizontal lines in the LVGL draw buffer. 20-40 lines is a reasonable starting
// point for a ${Math.round(target.width)}x${Math.round(target.height)} panel; raise it (uses more RAM) if you see tearing, lower it
// (uses less RAM) if you're tight on memory. See README.md's "Display buffer size" section.
#define ${macroPrefix}_DRAW_BUFFER_LINES 20

// ---------------------------------------------------------------------------------------------
// Display wiring — from the display model chosen in the Export dialog (${DISPLAY_MODEL_LABELS[target.displayModel]}).
// EDIT THESE if your wiring differs, or remove them entirely if your display driver library
// configures pins elsewhere (e.g. via User_Setup.h for TFT_eSPI).
// ---------------------------------------------------------------------------------------------
${pinLine(`${macroPrefix}_TFT_CS`, target.pins.cs)}
${pinLine(`${macroPrefix}_TFT_DC`, target.pins.dc)}
${pinLine(`${macroPrefix}_TFT_RST`, target.pins.rst)}
${pinLine(`${macroPrefix}_TFT_SCLK`, target.pins.sclk)}
${pinLine(`${macroPrefix}_TFT_MOSI`, target.pins.mosi)}
${pinLine(`${macroPrefix}_TFT_MISO`, target.pins.miso)}
${pinLine(`${macroPrefix}_TFT_BL`, target.pins.bl)}
`
}

